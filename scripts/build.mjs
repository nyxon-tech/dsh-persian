// Inline the Vazirmatn font into the single-file browser artifact the DSH module loader expects.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const font = readFileSync(join(root, 'assets', 'Vazirmatn-wght.woff2'))
const source = readFileSync(join(root, 'src', 'client.js'), 'utf8')
const marker = '__VAZIRMATN_WOFF2_BASE64__'
if (!source.includes(marker)) throw new Error(`src/client.js has no ${marker} marker`)
const output = source
  .replace('// Source of the browser half. `node scripts/build.mjs` inlines the font and writes ../client.js.\n',
    '// Generated by scripts/build.mjs from src/client.js; edit the source and rebuild.\n')
  .replace(marker, font.toString('base64'))
writeFileSync(join(root, 'client.js'), output)
console.log(`client.js written (${output.length} bytes, font ${font.length} bytes)`)
